import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const sourceExtension = /\.(?:astro|tsx?|md|scss|css)$/;
const generatedDirectory = '.astro/web-fonts';
const fontDefinitions = [
  { id: 'wenkai', family: 'LXGW WenKai Lite', source: 'LXGWWenKaiLite-Regular.ttf', weight: '400', homeOnly: true },
  { id: 'cinzel', family: 'Cinzel', source: 'Cinzel-VariableFont_wght.ttf', weight: '400 900' },
  { id: 'montecarlo', family: 'MonteCarlo', source: 'MonteCarlo-Regular.ttf', weight: '400' },
];

async function readSources(root, directory = 'src') {
  const sources = [];
  for (const entry of await readdir(path.join(root, directory), { withFileTypes: true })) {
    const relative = `${directory}/${entry.name}`;
    if (relative === 'src/generated' || relative.startsWith('src/assets/')) continue;
    if (entry.isDirectory()) sources.push(...await readSources(root, relative));
    else if (sourceExtension.test(entry.name)) sources.push({ path: relative, text: await readFile(path.join(root, relative), 'utf8') });
  }
  return sources.sort((a, b) => a.path.localeCompare(b.path));
}

/** Conservatively include source text, plus characters encoded in TS/HTML. */
export function collectFontCharacters(texts) {
  const decoded = texts.join('\n').replace(/\\u\{([\da-f]+)\}|\\u([\da-f]{4})|&#x([\da-f]+);|&#(\d+);/gi, (match, a, b, c, d) => {
    const code = parseInt(a || b || c || d, d ? 10 : 16);
    return code <= 0x10ffff ? String.fromCodePoint(code) : match;
  });
  // ASCII also covers client-generated counters and navigation labels.
  return [...new Set([...decoded, ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(i + 32))])]
    .filter(char => char.codePointAt(0) >= 32)
    .sort((a, b) => a.codePointAt(0) - b.codePointAt(0)).join('');
}

async function writeChanged(file, content) {
  try { if (await readFile(file, 'utf8') === content) return; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await writeFile(file, content);
}

/** Build-only dependency: no font processing or complete TTF reaches the browser. */
export async function prepareWebFonts(root) {
  const directory = path.join(root, generatedDirectory);
  await mkdir(directory, { recursive: true });
  const sources = await readSources(root);
  const lock = await readFile(path.join(root, 'package-lock.json'));
  const manifest = [];
  const css = ['// Generated by scripts/web-fonts.mjs; edit the original fonts, not this cache.'];
  for (const definition of fontDefinitions) {
    // WenKai is the homepage prose face; the other faces serve labels site-wide.
    const texts = sources.filter(source => !definition.homeOnly || source.path.startsWith('src/components/home/') || source.path === 'src/config/pages/home.ts');
    const characters = collectFontCharacters(texts.map(source => source.text));
    const original = await readFile(path.join(root, 'src/assets/fonts', definition.source));
    const digest = createHash('sha256').update('web-fonts-v1').update(original).update(characters).update(lock).digest('hex').slice(0, 16);
    const file = `${definition.id}.${digest}.woff2`;
    let buffer;
    try { buffer = await readFile(path.join(directory, file)); }
    catch (error) {
      if (error.code !== 'ENOENT') throw error;
      buffer = await subsetFont(original, characters, {
        targetFormat: 'woff2',
        preserveNameIds: [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17],
      });
      await writeFile(path.join(directory, file), buffer);
    }
    css.push(`@font-face {
  font-family: "${definition.family}";
  font-style: normal;
  font-weight: ${definition.weight};
  font-display: swap;
  src: url("../../${generatedDirectory}/${file}") format("woff2");
}`);
    manifest.push({ id: definition.id, file, bytes: buffer.length, sourceBytes: original.length, sourceSha256: createHash('sha256').update(original).digest('hex'), characters });
  }
  await writeChanged(path.join(directory, 'fonts.scss'), css.join('\n\n') + '\n');
  await writeChanged(path.join(directory, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

/** @returns {import('astro').AstroIntegration} */
export default function webFonts() {
  let root;
  return {
    name: 'telysta-web-fonts',
    hooks: {
      'astro:config:setup': async ({ config, command, logger }) => {
        if (command === 'preview') return;
        root = fileURLToPath(config.root);
        const fonts = await prepareWebFonts(root);
        logger.info(fonts.map(font => `${font.id}: ${(font.bytes / 1024).toFixed(1)} KiB`).join(', '));
      },
      'astro:server:setup': ({ server, logger }) => {
        let pending = Promise.resolve();
        const update = (event, file) => {
          const relative = path.relative(root, file).replaceAll('\\', '/');
          if (!['add', 'change', 'unlink'].includes(event) || !relative.startsWith('src/') || relative.startsWith('src/generated/') || !sourceExtension.test(file)) return;
          pending = pending.then(() => prepareWebFonts(root)).then(() => {}).catch(error => logger.error(String(error)));
        };
        server.watcher.on('all', update);
        server.httpServer?.once('close', () => server.watcher.off('all', update));
      },
    },
  };
}
